"""Rebuild checked-in JSON Schemas and TypeScript: python -m app.contracts.export."""

import json
from pathlib import Path

from pydantic import TypeAdapter

from . import models
from .common import (
    VERSION,
    ApprovalAction,
    Contract,
    DecisionOutcome,
    ProposalState,
    RequestUnit,
    TrustLevel,
)
from .reasons import REASON_REGISTRY, ReasonDefinition, ReasonEffect
from .trust import Conflict, TrustLabel, TrustSource

ROOT = Path(__file__).resolve().parents[3]
SCHEMA_MODELS = (
    TrustSource, Conflict, TrustLabel,
    *(model for model in vars(models).values()
      if isinstance(model, type) and issubclass(model, Contract) and model.__module__ == models.__name__),
    ReasonDefinition,
)
AGENT_MODELS = tuple(model for model in SCHEMA_MODELS if model is not models.ApproverView)


def schemas() -> dict[str, dict]:
    return {
        model.__name__: {
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "$id": f"urn:aimo-connect:v{VERSION}:{model.__name__}",
            "x-contract-version": VERSION,
            **model.model_json_schema(mode="serialization"),
        }
        for model in SCHEMA_MODELS
    }


def _ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(_ts_type(part) for part in schema["anyOf"])
    kind = schema.get("type")
    if kind == "object":
        if "properties" in schema:
            required = set(schema.get("required", []))
            fields = [
                f"  {name}{'' if name in required else '?'}: {_ts_type(field)};"
                for name, field in schema["properties"].items()
            ]
            return "{\n" + "\n".join(fields) + "\n}"
        return "{ [key: string]: " + _ts_type(schema.get("additionalProperties", {})) + " }"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(_ts_type(item) for item in schema["prefixItems"]) + "]"
        return f"Array<{_ts_type(schema.get('items', {}))}>"
    if kind in ("integer", "number"):
        return "number"
    if kind in ("string", "boolean", "null"):
        return kind
    if not schema:
        return "unknown"
    raise ValueError(f"Unsupported schema in TypeScript export: {schema}")


def typescript(exported: dict[str, dict]) -> str:
    definitions: dict[str, dict] = {}
    for name, schema in exported.items():
        for dependency, definition in schema.get("$defs", {}).items():
            if dependency in definitions and definitions[dependency] != definition:
                raise ValueError(f"Inconsistent schema definition: {dependency}")
            definitions[dependency] = definition
        definitions[name] = {
            key: value for key, value in schema.items() if not key.startswith(("$", "x-"))
        }
    for name, alias in {
        "ApprovalAction": ApprovalAction, "DecisionOutcome": DecisionOutcome,
        "ProposalState": ProposalState, "RequestUnit": RequestUnit, "TrustLevel": TrustLevel,
        "ReasonEffect": ReasonEffect,
    }.items():
        definitions[name] = TypeAdapter(alias).json_schema(mode="serialization")
    header = (
        "// Generated by python -m app.contracts.export. Do not edit.\n"
        "// v0.1 wire values: money/quantities are decimal strings; dates/times are ISO strings.\n"
    )
    declarations = [f"export type {name} = {_ts_type(schema)};" for name, schema in sorted(definitions.items())]
    registry = {code.value: reason.model_dump(mode="json") for code, reason in REASON_REGISTRY.items()}
    return header + "\n\n".join(declarations) + (
        "\n\nexport const REASON_REGISTRY = " + json.dumps(registry, indent=2, ensure_ascii=False)
        + " as const satisfies Record<ReasonCode, ReasonDefinition>;\n"
    )


def main() -> None:
    exported = schemas()
    directory = ROOT / "spec/schemas"
    directory.mkdir(parents=True, exist_ok=True)
    for name, schema in exported.items():
        (directory / f"{name}.json").write_text(
            json.dumps(schema, indent=2, ensure_ascii=False) + "\n", encoding="utf-8",
        )
    (ROOT / "frontend/src/lib/contracts.ts").write_text(typescript(exported), encoding="utf-8")


if __name__ == "__main__":
    main()
